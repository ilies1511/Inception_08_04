#!/bin/bash

cat > /etc/mysql/init.sql << EOF
CREATE DATABASE $DB_DATABASE;
CREATE USER IF NOT EXISTS '$DB_WPUSER'@'%' IDENTIFIED BY '$DB_WPPASS';
GRANT ALL PRIVILEGES ON *.* TO '$DB_WPUSER'@'%' WITH GRANT OPTION;
FLUSH PRIVILEGES;
EOF

mysql_install_db
mysqld


