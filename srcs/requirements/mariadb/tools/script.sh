#!/bin/bash

cat > /etc/mysql/init.sql << EOF
CREATE DATABASE $DB_DATABASE;
CREATE USER '$DB_WPUSER'@'%' IDENTIFIED BY '$DB_WPPASS';
GRANT ALL PRIVILEGES ON *.* TO '$DB_WPUSER'@'%' WITH GRANT OPTION;
ALTER USER 'root'@'localhost' IDENTIFIED BY '$MYSQL_ROOT_PASS';
FLUSH PRIVILEGES;
EOF

mysql_install_db
mysqld


